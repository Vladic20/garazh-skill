#!/usr/bin/env node
// One command: story.json → narrated, rendered, mixed mp4.
//   node make.mjs <ep>                     full film, 1920×1080 → out/<ep>.mp4 (+ out/<ep>.srt)
//   node make.mjs <ep> --preview           fast 1280×720 draft → out/<ep>_preview.mp4
//   node make.mjs <ep> --stills auto       one PNG per scene + contact sheet → episodes/<ep>/build/sheet.png (no video)
//   node make.mjs <ep> --stills 1.5,7,12   PNGs at those seconds
//   --offline        never call the TTS API (cached lines play, new lines get estimated timing and no audio)
//   --jobs N         parallel Chrome workers (default: cpu-2, max 6)
//   --out file.mp4   output path
// Keys are read from .env next to this file: OPENROUTER_API_KEY (recommended) or FISH_AUDIO_API_KEY.
import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { cpus } from 'node:os';
import path from 'node:path';
import { buildTimeline, toSrt } from './lib/story.mjs';
import { buildVoice, DEFAULT_VOICE, DEFAULT_MODEL, provider } from './lib/voice.mjs';
import { voiceStem, bedStem, muxFinal } from './lib/audio.mjs';
import { renderStills, renderVideo } from './lib/frames.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const fail = m => { console.error(`\n✗ ${m}`); process.exit(1); };
const opt = (n, d) => { const i = argv.indexOf(n); return i < 0 ? d : argv[i + 1]; };
const flag = n => argv.includes(n);

// .env loader (no dependency, no --env-file needed); real environment wins
const envFile = path.join(root, '.env');
if (existsSync(envFile)) for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/); if (!m || process.env[m[1]]) continue;
  process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
}

const ep = argv.find(a => !a.startsWith('--') && !['--stills', '--jobs', '--out'].includes(argv[argv.indexOf(a) - 1]));
if (!ep || flag('--help')) { console.log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 11).join('\n').replace(/^\/\/ ?/gm, '')); process.exit(ep ? 0 : 1); }
if (!/^[\w-]+$/.test(ep)) fail(`episode name: latin letters, digits, - and _ only (got "${ep}")`);
const epDir = path.join(root, 'episodes', ep), storyFile = path.join(epDir, 'story.json');
if (!existsSync(storyFile)) fail(`no ${path.relative(root, storyFile)} — write the story first (see episodes/demo/story.json)`);
for (const tool of ['ffmpeg', 'ffprobe']) if (spawnSync(tool, ['-version']).error) fail(`${tool} not found in PATH`);

let story;
try { story = JSON.parse(readFileSync(storyFile, 'utf8')); } catch (e) { fail(`story.json is not valid JSON: ${e.message}`); }
const PREVIEW = flag('--preview'), STILLS = opt('--stills', null), OFFLINE = flag('--offline') || !!STILLS && !provider();
const JOBS = +opt('--jobs', Math.max(1, Math.min(6, cpus().length - 2)));
const buildDir = path.join(epDir, 'build'); mkdirSync(buildDir, { recursive: true });
const T0 = Date.now(), el = () => `${((Date.now() - T0) / 1000).toFixed(1)}s`;

// 1) narration
const voice = story.voice || process.env.TVHEAD_VOICE || DEFAULT_VOICE, model = story.model || DEFAULT_MODEL;
const style = story.style ? `[${String(story.style).replace(/^\[|\]$/g, '')}] ` : '';
const lines = story.scenes.map(s => ({ text: s.say ? (s.say.trim().startsWith('[') || !style ? s.say.trim() : style + s.say.trim()) : '' }));
console.log(`▸ ${ep}: ${story.scenes.length} scenes · voice ${voice} · ${model} · provider ${OFFLINE ? 'offline' : provider() || 'none (no key)'}`);
let V;
try { V = await buildVoice({ lines, voice, model, cacheDir: path.join(epDir, 'voice'), offline: OFFLINE }); }
catch (e) { fail(`voice: ${e.message}`); }

// 2) timeline
const TL = buildTimeline(story, V.clips);
writeFileSync(path.join(buildDir, 'timeline.js'), `// generated by make.mjs from story.json — do not edit\nwindow.TL = ${JSON.stringify(TL)};\n`);
const tlRel = path.relative(path.join(root, 'engine'), path.join(buildDir, 'timeline.js')).split(path.sep).join('/');
console.log(`▸ timeline: ${TL.duration.toFixed(1)}s, ${TL.scenes.length} scenes, ${TL.subs.length} caption phrases (${el()})`);

// 3a) stills + contact sheet
if (STILLS) {
  const times = STILLS === 'auto' ? TL.scenes.map(s => +(s.from + Math.min(s.to - s.from - .05, Math.max(.9, (s.to - s.from) * .7))).toFixed(2)) : STILLS.split(',').map(Number);
  if (times.some(t => !Number.isFinite(t) || t < 0)) fail(`--stills: seconds separated by commas, or "auto"`);
  const dir = path.join(buildDir, 'stills'); rmSync(dir, { recursive: true, force: true });
  try {
    const files = await renderStills({ root, tlRel, times, outDir: dir, dsf: 1 });
    const cols = Math.min(4, files.length), rows = Math.ceil(files.length / cols);
    spawnSync('ffmpeg', ['-y', '-v', 'error', '-framerate', '1', '-i', path.join(dir, 's_%03d.png'), '-vf', `scale=480:-1,tile=${cols}x${rows}:padding=6:color=0x222222`, '-frames:v', '1', path.join(buildDir, 'sheet.png')]);
    files.forEach((f, i) => console.log(`  still ${times[i].toFixed(2)}s → ${path.relative(root, f)}`));
    console.log(`✓ contact sheet → ${path.relative(root, path.join(buildDir, 'sheet.png'))} (${el()})`);
  } catch (e) { fail(e.message); }
  process.exit(0);
}

// 3b) video
const outDir = path.join(root, 'out'); mkdirSync(outDir, { recursive: true });
const out = path.resolve(opt('--out', path.join(outDir, `${ep}${PREVIEW ? '_preview' : ''}.mp4`)));
const silent = path.join(buildDir, 'video.mp4');
try {
  const r = await renderVideo({ root, tlRel, duration: TL.duration, out: silent, dsf: PREVIEW ? 1 : 1.5, jobs: JOBS, preset: PREVIEW ? 'veryfast' : 'faster', crf: PREVIEW ? 26 : 23,
    onProgress: (d, n, s) => process.stdout.write(`\r▸ frames ${d}/${n}  ${(d / s).toFixed(1)} fps  `) });
  console.log(`\r▸ frames ${r.frames}/${r.frames} → ${r.size.join('×')} in ${r.seconds.toFixed(1)}s            `);
} catch (e) { fail(`render: ${e.message}`); }

// 4) sound
const voiceWav = path.join(buildDir, 'voice.wav'), bedWav = path.join(buildDir, 'bed.wav');
try {
  const hasVoice = voiceStem(TL.voice, TL.duration, voiceWav);
  bedStem({ duration: TL.duration, mood: story.mood ?? 'dark', cuts: story.flips === false ? [] : TL.scenes.slice(1).map(s => s.from), music: story.music, root: epDir }, bedWav);
  muxFinal({ video: silent, voiceWav, bedWav, out, hasVoice });
} catch (e) { fail(`audio: ${e.message}`); }
writeFileSync(out.replace(/\.mp4$/, '.srt'), toSrt(TL.subs));

const probe = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:stream=codec_type,width,height', '-of', 'json', out], { encoding: 'utf8' });
const info = JSON.parse(probe.stdout || '{}'), vs = (info.streams || []).find(s => s.codec_type === 'video');
console.log(`✓ ${out}\n  ${vs ? `${vs.width}×${vs.height}` : '?'} · ${(+info.format?.duration || 0).toFixed(1)}s · ${(statSync(out).size / 1048576).toFixed(1)} MB · ` +
  `${V.estimated ? `⚠ ${V.estimated} line(s) silent (no TTS key)` : `voice: ${V.generated} new line(s), rest from cache`} · total ${el()}`);
